//! 辞書を持つプロセス。
//!
//! TIP は入力先アプリの中で動く。辞書をそこに載せると、**Word にも Chrome
//! にも写しが一つずつ載る**。隔離されたアプリからはファイルに触れず、
//! ユーザー辞書の書き手も数えきれなくなる。
//!
//! そこで辞書はこのプロセスだけが持つ (ADR-0016)。TIP は引きたいものを
//! 名前付きパイプ越しに頼む。
//!
//! # 逃げ道は作らない
//!
//! 繋がらなかったときに TIP が自分で辞書を読む、という道は**用意しない**。
//! 読み手が二つになれば書き手も二つになり、学習が壊れる。めったに通らない
//! 道は腐りもする。
//!
//! 代わりに、**居ないほうを起きにくくする**。導入がその場で起こし、ログオン
//! でも立ち上がり、TIP は繋がらなければ短く待ってもう一度試す。それでも
//! 駄目なら、黙って違う結果を出さずに**繋がらないと言う**。

